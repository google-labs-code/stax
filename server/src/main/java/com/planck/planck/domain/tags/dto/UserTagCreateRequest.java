package com.planck.planck.domain.tags.dto;

import com.fasterxml.jackson.annotation.JsonInclude;
import com.fasterxml.jackson.annotation.JsonInclude.Include;
import com.fasterxml.jackson.annotation.JsonProperty;
import com.fasterxml.jackson.databind.PropertyNamingStrategies;
import com.fasterxml.jackson.databind.annotation.JsonNaming;
import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.constraints.NotNull;
import java.io.Serializable;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
@JsonNaming(PropertyNamingStrategies.SnakeCaseStrategy.class)
@JsonInclude(Include.NON_NULL)
public class UserTagCreateRequest implements Serializable {

  private static final long serialVersionUID = 6822277293482753178L;

  @Schema(description = "Name of the tag", example = "myTag")
  @NotNull(message = "Tag name cannot be null")
  @JsonProperty("name")
  private String name;

  @Schema(description = "Color of the tag", example = "#FFFFFF")
  @JsonProperty("color")
  private String color;
}
