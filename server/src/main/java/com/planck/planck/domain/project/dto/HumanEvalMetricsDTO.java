package com.planck.planck.domain.project.dto;

import io.swagger.v3.oas.annotations.media.Schema;
import java.util.Map;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
public class HumanEvalMetricsDTO {
  @Schema(description = "Counts of human evaluation scores grouped by score value")
  private Map<Integer, Long> scoreCounts;

  @Schema(
      description =
          "Human pass rate: count of scores with value 1 divided by count of all non-null scores")
  private Double passRate;
}
