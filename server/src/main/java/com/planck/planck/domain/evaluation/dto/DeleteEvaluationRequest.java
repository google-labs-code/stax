package com.planck.planck.domain.evaluation.dto;

import com.fasterxml.jackson.annotation.JsonProperty;
import io.swagger.v3.oas.annotations.media.Schema;
import java.util.List;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

@Data
@Builder
@AllArgsConstructor
@NoArgsConstructor
@Schema(description = "Request to delete an evaluation")
public class DeleteEvaluationRequest {

  @Schema(
      description = "List of response IDs to delete evaluations for",
      example = "[\"llm-eval-uuid4_1\", \"llm-eval-uuid4_2\"]")
  @JsonProperty("response_ids")
  List<String> responseIds;
}
